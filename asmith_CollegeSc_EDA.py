import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns
from matplotlib.ticker import PercentFormatter # To format y-axis as percentages

# Load the dataset with the relevant variable
df_acceptance_rate = pd.read_csv(
    "CollegeScorecardData_1996-2023.csv",
    usecols=["ADM_RATE_SUPP"]
)

# Drop rows where the acceptance rate data is missing
# It's important to remove NaNs as they cannot be plotted.
df_acceptance_rate_clean = df_acceptance_rate.dropna(
    subset=["ADM_RATE_SUPP"]
)

# Convert acceptance rate to percentage (0-100 scale) for better readability
# Assuming 'ADM_RATE_SUPP' is a proportion between 0 and 1.
df_acceptance_rate_clean['ADM_RATE_SUPP_PCT'] = df_acceptance_rate_clean['ADM_RATE_SUPP'] * 100

# --- Create the Scatterplot (Strip Plot) ---
plt.figure(figsize=(10, 7))

# Use sns.stripplot to create a scatterplot of individual data points.
# We assign all data points to a single 'category' on the x-axis to show their distribution.
sns.stripplot(
    y=df_acceptance_rate_clean['ADM_RATE_SUPP_PCT'],
    x=['All Institutions'] * len(df_acceptance_rate_clean), # Dummy category for x-axis
    jitter=0.2, # Adds random noise to x-position to prevent overplotting
    color='purple', # Color of the points
    alpha=0.6, # Transparency of the points
    size=4 # Size of the points
)

# Add titles and labels for clarity
plt.title(
    'Scatterplot of Acceptance Rates Across Institutions (Fall 2023 Cohort)',
    fontsize=16
)
plt.xlabel('') # No meaningful x-label as it's a single category
plt.ylabel(
    'Acceptance Rate (%)',
    fontsize=12
)

# Format the y-axis ticks to display as percentages (e.g., 50% instead of 50.0)
plt.gca().yaxis.set_major_formatter(PercentFormatter(xmax=100))

plt.grid(axis='y', linestyle='--', alpha=0.7) # Add a grid for better readability
plt.tight_layout() # Adjust layout to prevent labels from overlapping
plt.show()

# Print some descriptive statistics for context
print(f"Total institutions with available acceptance rate data: {len(df_acceptance_rate_clean)}")
print(f"Overall Median Acceptance Rate: {df_acceptance_rate_clean['ADM_RATE_SUPP_PCT'].median():.2f}%")
print(f"Average Acceptance Rate: {df_acceptance_rate_clean['ADM_RATE_SUPP_PCT'].mean():.2f}%")
print(f"Range of Acceptance Rates: {df_acceptance_rate_clean['ADM_RATE_SUPP_PCT'].min():.2f}% - {df_acceptance_rate_clean['ADM_RATE_SUPP_PCT'].max():.2f}%")

