import pandas as pd
import matplotlib.pyplot as plt

# Read the dataset
df = pd.read_csv("CollegeScorecardData_1996-2023.csv", usecols=['CITY'])

# Count the number of institutions per city and get the top 4
top_cities = df['CITY'].value_counts().nlargest(4)

# Optional: add state abbreviations if desired (manually for common cases)
city_labels = {
    'New York': 'New York, NY',
    'Los Angeles': 'Los Angeles, CA',
    'Chicago': 'Chicago, IL',
    'Houston': 'Houston, TX',
    'Phoenix': 'Phoenix, AZ',
    'Montgomery': 'Montgomery, AL',
    'Denver': 'Denver, CO',
    'Claremont': 'Claremont, CA'
}

# Replace labels with city + state if found in the mapping
renamed_index = [city_labels.get(city, city) for city in top_cities.index]

# Calculate the total number of institutions in the top 4 cities
total_top_cities_count = top_cities.sum()

# Define a function to format the autopct to show both percentage and count
def autopct_format_with_count(pct):
    # Calculate the actual count from the percentage
    absolute_count = int(round(pct/100.*total_top_cities_count))
    return f'{pct:.1f}%\n({absolute_count:d})'

# Plot pie chart
plt.figure(figsize=(7,7))
plt.pie(top_cities, labels=renamed_index, autopct=autopct_format_with_count, startangle=140, colors=plt.cm.Paired.colors)
plt.title('Where are the majority of US Colleges? | Top 4 US Cities with Highest Number of Colleges (1996-2023)')
plt.axis('equal')
plt.show()

